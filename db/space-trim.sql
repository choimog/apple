-- ===========================================================================
--  기준 밖 순위 자료 정리 — 일간 300위 · 주간 500위
-- ===========================================================================
--  【대표님 결정 — 2026-08-11】
--  "일간은 매일 300위권, 주간은 매일 500위권까지 취합하는 걸로 하고,
--   현재 이 기준에서 벗어난 순위권의 데이터는 지우는 걸로 하면
--   더 오래 버틸 수 있으려나?"
--
--  네, 훨씬 오래 버팁니다. 앞으로 모을 양은 config/sources.yaml 에서
--  이미 줄여 두었고(146개 분야), 이 파일은 **이미 쌓인 것**을 정리합니다.
--
--  【무엇을 지우나요?】
--   ① 일간 301위 이하 · 주간 501위 이하의 순위 기록
--   ② 그래서 순위에 한 줄도 안 남은 상품 정보
--   ③ 그래서 딸린 책이 하나도 없어진 도서 묶음
--
--  ⚠️⚠️ 대표님이 손으로 내리신 결정(같은 책 / 다른 책)이 걸린 상품은
--        **절대 안 지웁니다.** 지금 book_matches 에 manual_merge 38,161줄,
--        manual_split 47,054줄이 있습니다. 상품을 지우면 데이터베이스가
--        그 결정까지 **함께 지워 버립니다**(ON DELETE CASCADE).
--        8만 5천 건의 검토가 한순간에 사라집니다.
--        그래서 ② 에서 그런 상품은 남깁니다. 아래 조건을 지우지 마세요.
--
--  【얼마나 오래 버티나요?】
--   · 하루에 저장되는 순위 줄  121,910 → 약 46,900 (62% 감소)
--   · 순위표 14일치           약 189MB → 약 73MB
--   · 새 상품 유입            하루 19,750줄 → 크게 줄어듭니다
--     (뒤쪽 순위일수록 매일 갈리기 때문입니다. 정확한 수치는 며칠
--      지나 db/space-growth.sql 로 다시 재 봐야 압니다. 지금 숫자를
--      지어내지 않겠습니다)
--
--  【지운 자리는 바로 줄어드나요?】
--   순위표는 **바로는 안 줄어듭니다.** PostgreSQL 은 지운 자리를 '빈
--   자리' 로 표시해 두었다가 다음에 넣는 자료로 다시 채웁니다. 즉
--   **더 늘지 않는 것**이 효과입니다. (VACUUM FULL 로 즉시 돌려받을 수
--   있지만 Supabase SQL Editor 에서는 실행되지 않습니다)
--
--  【되돌릴 수 있나요?】
--   ❌ 없습니다. 지운 과거 순위는 사라집니다.
--      다만 14일이 지난 자료는 어차피 보관소(GitHub)로 빠져 있고,
--      그 파일에는 1,000위까지 그대로 들어 있습니다.
--      최근 14일치의 301~1000위만 사라지는 것입니다.
--
--  【얼마나 걸리나요?】 1~3분. 큰 표를 지우기 때문입니다.
--
--  실행: Supabase → SQL Editor → New query → 전체 붙여넣고 Run
--        표 하나가 나옵니다. 그대로 알려 주세요.
-- ===========================================================================

-- ---------------------------------------------------------------------------
--  ① 기준 밖 순위 기록
-- ---------------------------------------------------------------------------
--  categories.kind 로 일간·주간을 가릅니다.
--    'weekly'  → 500위까지 남김
--    그 밖     → 300위까지 남김 (online / offline)
-- ---------------------------------------------------------------------------
DELETE FROM rankings r
 USING categories c
 WHERE c.id = r.category_id
   AND r.rank > CASE WHEN c.kind = 'weekly' THEN 500 ELSE 300 END;


-- ---------------------------------------------------------------------------
--  ② 순위에 한 줄도 안 남은 상품
-- ---------------------------------------------------------------------------
--  🚨 대표님 결정이 걸린 상품은 뺍니다. 지우면 결정도 함께 사라집니다.
-- ---------------------------------------------------------------------------
DELETE FROM store_books s
 WHERE NOT EXISTS (SELECT 1 FROM rankings r WHERE r.store_book_id = s.id)
   AND NOT EXISTS (
        SELECT 1 FROM book_matches m
         WHERE m.decision IN ('manual_merge', 'manual_split')
           AND (m.store_book_a = s.id OR m.store_book_b = s.id));


-- ---------------------------------------------------------------------------
--  ③ 딸린 책이 하나도 없어진 도서 묶음
-- ---------------------------------------------------------------------------
DELETE FROM books b
 WHERE NOT EXISTS (SELECT 1 FROM store_books s WHERE s.book_id = b.id);


-- ---------------------------------------------------------------------------
--  확인
-- ---------------------------------------------------------------------------
SELECT "번호", "항목", "값" FROM (
    SELECT 1 AS "번호", '남은 순위 줄' AS "항목",
           to_char((SELECT count(*) FROM rankings), 'FM999,999,999') AS "값"
    UNION ALL
    SELECT 2, '  └ 기준을 넘는 줄',
           to_char((SELECT count(*) FROM rankings r JOIN categories c ON c.id = r.category_id
                     WHERE r.rank > CASE WHEN c.kind = 'weekly' THEN 500 ELSE 300 END),
                   'FM999,999,999') || ' (0이면 성공)'
    UNION ALL
    SELECT 3, '남은 상품',
           to_char((SELECT count(*) FROM store_books), 'FM999,999,999')
    UNION ALL
    SELECT 4, '남은 도서 묶음',
           to_char((SELECT count(*) FROM books), 'FM999,999,999')
    UNION ALL
    -- 🚨 이 숫자가 줄었으면 큰일입니다. 8만 5천 건이 그대로 있어야 합니다.
    SELECT 5, '🚨 대표님이 내리신 결정',
           to_char((SELECT count(*) FROM book_matches
                     WHERE decision IN ('manual_merge', 'manual_split')),
                   'FM999,999,999') || '건 (줄었으면 알려 주세요)'
    UNION ALL
    SELECT 6, '지금 전체 용량',
           pg_size_pretty(sum(pg_total_relation_size(c.oid)))
      FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
     WHERE n.nspname = 'public' AND c.relkind = 'r'
) x ORDER BY "번호";
