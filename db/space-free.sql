-- ===========================================================================
--  자료를 하나도 안 잃고 용량 되찾기 — 약 31MB
-- ===========================================================================
--  【무엇을 지우나요?】
--  대표님이 보시는 화면에 나오는 자료는 **하나도 안 건드립니다.**
--  아무도 안 읽는 것과, 만들어 놓고 한 번도 안 쓴 '목차' 만 정리합니다.
--
--   ① book_meta (24MB · 85,508줄)
--      해시태그와 이벤트 문구입니다. 코드 전체를 뒤져서 확인했는데
--      **사이트·AI 리포트·매칭 어디에서도 이 표를 읽지 않습니다.**
--      무료 500MB 중 24MB(5%)를 아무도 안 보는 자료가 쓰고 있었습니다.
--      → 비웁니다. 표는 남겨 두므로 나중에 화면에서 쓰기로 하시면
--        config/sources.yaml 의 save_book_meta 를 true 로 바꾸는 것만으로
--        그날부터 다시 쌓입니다. (서점에 요청을 더 보내지 않습니다)
--
--      ⚠️ 지금까지 모은 해시태그·이벤트 문구는 **되살릴 수 없습니다.**
--         쓰는 곳이 없어서 지우는 것이지만, 그래도 지우는 것은 지우는
--         것입니다. 나중에 쓸 생각이 조금이라도 있으시면 아래
--         ① 부분만 빼고 실행하세요. (② 만 해도 6.6MB 는 나옵니다)
--
--   ② idx_store_books_block (6.6MB)
--      '빨리 찾기용 목차' 입니다. 자료가 아닙니다.
--      만들어 놓고 **한 번도 안 썼습니다**(읽힌 횟수 0). 매칭은 이
--      목차를 데이터베이스에서 쓰는 게 아니라 프로그램 안에서 직접
--      계산합니다. 지워도 느려지는 곳이 없습니다.
--      → 나중에 필요하면 db/schema.sql 에 만드는 문장이 그대로
--        남아 있으니 한 줄로 되살릴 수 있습니다.
--
--  【얼마나 걸리나요?】 10~30초.
--  【지금 당장 급한가요?】
--  이것만으로는 2~3일 벌 뿐입니다. 하루 12MB 씩 늘고 있어서 근본
--  대책(오래된 상품 정리 또는 순위 깊이 줄이기)이 따로 필요합니다.
--  다만 **잃는 것이 없으므로** 먼저 해 두는 편이 좋습니다.
--
--  실행: Supabase → SQL Editor → New query → 전체 붙여넣고 Run
--        표 하나가 나옵니다. 그대로 알려 주세요.
-- ===========================================================================

-- ① 아무도 안 읽는 해시태그·이벤트 기록을 비웁니다.
--    ⚠️ 이 줄을 실행하기 전에 crawler 쪽 save_book_meta 가 false 인지
--       확인하세요. 안 그러면 내일 새벽 수집이 다시 채웁니다.
--       (2026-08-11 커밋에서 이미 false 로 바꿔 두었습니다)
TRUNCATE TABLE book_meta;

-- ② 만들어 놓고 한 번도 안 쓴 목차를 지웁니다. 자료가 아닙니다.
DROP INDEX IF EXISTS idx_store_books_block;

-- ⚠️ 여기에 VACUUM FULL 을 쓰면 안 됩니다.
--    Supabase SQL Editor 는 붙여넣은 것을 **한 덩어리(트랜잭션)** 로 돌리는데,
--    VACUUM 은 그 안에서 못 돕니다. "VACUUM cannot run inside a transaction
--    block" 이라며 죽고, **앞의 TRUNCATE 까지 통째로 되돌아갑니다.**
--    (처음에 넣어 뒀다가 알아채고 뺐습니다. 제 컴퓨터의 psql 로는
--     통과해서 시험도 속았습니다. 시험 쪽에도 막는 규칙을 넣어 뒀습니다)
--
--    다행히 TRUNCATE 는 그 자체로 자리를 바로 돌려줍니다.
--    DROP INDEX 도 마찬가지입니다. 그래서 VACUUM 이 필요 없습니다.


-- ---------------------------------------------------------------------------
--  확인 — 얼마나 돌려받았나
-- ---------------------------------------------------------------------------
SELECT "번호", "항목", "값" FROM (
    SELECT 1 AS "번호", 'book_meta 줄 수' AS "항목",
           (SELECT count(*)::text FROM book_meta) || '줄 (0줄이면 성공)' AS "값"
    UNION ALL
    SELECT 2, 'book_meta 크기',
           pg_size_pretty(pg_total_relation_size('book_meta'))
    UNION ALL
    SELECT 3, '안 쓰던 목차',
           CASE WHEN EXISTS (
               SELECT 1 FROM pg_class WHERE relname = 'idx_store_books_block')
                THEN '❌ 아직 있습니다' ELSE '✅ 지웠습니다' END
    UNION ALL
    SELECT 4, '지금 전체 용량',
           pg_size_pretty(sum(pg_total_relation_size(c.oid)))
      FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
     WHERE n.nspname = 'public' AND c.relkind = 'r'
) x ORDER BY "번호";
