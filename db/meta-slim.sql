-- ===========================================================================
--  book_meta 를 '날짜별' 에서 '책별 한 줄' 로 — 2026-08-10 대표님 승인
-- ===========================================================================
--  【왜 하나요?】
--  대표님이 실행해 주신 db/size-check.sql 결과입니다.
--
--      전체 줄            131,351
--      그 책을 처음 본 날  68,426   ← 꼭 필요
--      어제와 똑같은 줄    60,685   ← 46.2%, 순수 낭비
--      실제로 바뀐 줄       2,240   ← 1.7%
--
--  해시태그와 이벤트 문구는 거의 안 바뀌는데 **매일 새 줄로 다시**
--  저장하고 있었습니다. 게다가 확인해 보니 이 자료를 **사이트 어디에서도
--  읽지 않습니다.** 아무도 안 보는 기록에 용량을 쓰고 있었습니다.
--
--  【무엇이 달라지나요?】
--  · 책마다 한 줄만 남깁니다 (최신 값). 바뀌면 덮어씁니다.
--  · 잃는 것: "8월 3일엔 어떤 해시태그였나" 라는 **과거 기록**
--  · 화면 변화: **없습니다** (원래 안 쓰던 자료라서)
--
--  【안전한가요?】
--  줄을 지웁니다. 다만 **각 책의 가장 최근 줄은 반드시 남깁니다.**
--  실행 전후 줄 수를 표로 보여 드리니 눈으로 확인하실 수 있습니다.
--  ⚠️ 되돌릴 수 없습니다. 지워지는 것은 과거 날짜의 해시태그 기록입니다.
--
--  실행: Supabase → SQL Editor → New query → 전체 붙여넣고 Run
--        ※ 먼저 db/schema.sql 이 실행되어 있어야 합니다
-- ===========================================================================


-- ---------------------------------------------------------------------------
--  0. 하기 전 상태를 적어 둡니다 (나중에 비교용)
-- ---------------------------------------------------------------------------
CREATE TEMP TABLE _before AS
SELECT count(*) AS rows_before,
       count(DISTINCT store_book_id) AS books_before
FROM book_meta;


-- ---------------------------------------------------------------------------
--  1. 책마다 **가장 최근 줄만** 남기고 나머지를 지웁니다
-- ---------------------------------------------------------------------------
--  ⚠️ 부등호 방향이 생명입니다. a 가 b 보다 **오래된** 것만 지웁니다.
--     방향이 반대면 최신 것이 지워지고 옛것만 남습니다.
-- ---------------------------------------------------------------------------
DELETE FROM book_meta a
 USING book_meta b
 WHERE a.store_book_id = b.store_book_id
   AND a.snapshot_date < b.snapshot_date;


-- ---------------------------------------------------------------------------
--  2. 이제 '날짜' 는 열쇠가 아닙니다. 책 번호 하나가 열쇠입니다
-- ---------------------------------------------------------------------------
--  snapshot_date 는 지우지 않고 **'언제 본 값인지'** 로 남겨 둡니다.
--  나중에 "이 해시태그는 얼마나 오래된 것인가" 를 알 수 있어야 하니까요.
--  대신 열쇠(중복 방지 기준)에서만 뺍니다.
-- ---------------------------------------------------------------------------
ALTER TABLE book_meta DROP CONSTRAINT IF EXISTS book_meta_pkey;
ALTER TABLE book_meta ADD PRIMARY KEY (store_book_id);

COMMENT ON TABLE book_meta IS
  '책마다 한 줄 (최신 해시태그·이벤트). 2026-08-10 부터 날짜별로 쌓지 않습니다.';
COMMENT ON COLUMN book_meta.snapshot_date IS
  '이 값을 마지막으로 본 날. 열쇠가 아니라 참고용입니다.';


-- ---------------------------------------------------------------------------
--  3. 자리 돌려주기
-- ---------------------------------------------------------------------------
--  지운 자리는 곧바로 반납되지 않습니다. PostgreSQL 은 '빈 자리' 로만
--  표시해 두고 다음에 다시 씁니다. 그래서 **용량 숫자가 당장은 안 줄어들
--  수 있습니다.** 다만 이제부터 더 늘지 않습니다.
--
--  숫자까지 바로 줄이고 싶으시면, 이 파일을 다 돌린 **뒤에** 아래 한 줄만
--  따로 새 창에 붙여넣고 실행해 주세요 (같이 실행하면 거절당합니다).
--
--      VACUUM FULL book_meta;
--
--  몇 초에서 몇 분 걸리고, 그동안 이 표는 잠깁니다. 수집이 도는 시간대만
--  피하시면 됩니다.
-- ---------------------------------------------------------------------------
ANALYZE book_meta;


-- ---------------------------------------------------------------------------
--  4. 확인 — 눈으로 보고 넘어가 주세요
-- ---------------------------------------------------------------------------
SELECT * FROM (
    SELECT 1 AS "번호", '지우기 전 줄 수' AS "항목",
           to_char((SELECT rows_before FROM _before), 'FM999,999,999') AS "값"
    UNION ALL
    SELECT 2, '지운 뒤 줄 수',
           to_char((SELECT count(*) FROM book_meta), 'FM999,999,999')
    UNION ALL
    SELECT 3, '🚨 책 수가 그대로인가 (줄지 않아야 정상)',
           CASE WHEN (SELECT books_before FROM _before)
                     = (SELECT count(DISTINCT store_book_id) FROM book_meta)
                THEN '✅ ' || to_char((SELECT count(*) FROM book_meta),
                                      'FM999,999,999') || '권 그대로'
                ELSE '❌ 책이 사라졌습니다 — 저에게 알려 주세요' END
    UNION ALL
    SELECT 4, '🚨 한 책에 한 줄만 남았는가',
           CASE WHEN NOT EXISTS (
                    SELECT 1 FROM book_meta
                     GROUP BY store_book_id HAVING count(*) > 1)
                THEN '✅' ELSE '❌ 중복이 남아 있습니다' END
    UNION ALL
    SELECT 5, '열쇠가 책 번호 하나로 바뀌었는가',
           CASE WHEN (SELECT count(*) FROM pg_index i
                       JOIN pg_class c ON c.oid = i.indrelid
                       JOIN pg_attribute a
                         ON a.attrelid = c.oid AND a.attnum = ANY(i.indkey)
                      WHERE c.relname = 'book_meta' AND i.indisprimary) = 1
                THEN '✅' ELSE '❌ 이 파일을 다시 실행하세요' END
) x ORDER BY "번호";
